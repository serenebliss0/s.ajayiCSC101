    EMPLOYEE_ID INT PRIMARY KEY NOT NULL,
    EMPLOYEE_NAME TEXT NOT NULL,
    DEPARTMENT_NUMBER INT NOT NULL,
    EMPLOYEE_SALARY DECIMAL(10,2) NOT NULL,
    AGE INTEGER CHECK (AGE >= 0),
